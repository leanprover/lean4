#!/usr/bin/env python3
"""Generate browser bindings from the constants in UiAbi.lean."""

from pathlib import Path
import re

root = Path(__file__).parent
source = (root.parent / "UiAbi.lean").read_text()

def value(name: str) -> str:
    match = re.search(rf"(?:public )?def {name} : UInt32 := (0x[0-9a-fA-F]+|[0-9]+)", source)
    if not match:
        raise SystemExit(f"missing UInt32 constant {name}")
    return match.group(1)

top = {name: value(name) for name in ("magic", "version", "headerSize", "recordSize")}
effects = {name: value(name) for name in ("createElement", "createText", "setText", "remove", "setClass", "setHandler")}
handlers = {name: value(name) for name in ("none", "intro", "constructor", "cases", "undo", "reset", "exactBase")}

js = f'''// Generated by generate_ui_abi.py from UiAbi.lean.
export const UI_ABI = Object.freeze({{
  magic: {top["magic"]}, version: {top["version"]}, headerSize: {top["headerSize"]}, recordSize: {top["recordSize"]},
  effect: Object.freeze({{{", ".join(f" {k}: {v}" for k, v in effects.items())} }}),
  handler: Object.freeze({{{", ".join(f" {k}: {v}" for k, v in handlers.items())} }}),
}});

export function readUiBatch(memory, ptr) {{
  const view = new DataView(memory.buffer);
  const word = (offset) => view.getUint32(ptr + offset, true);
  const header = {{ magic: word(0), version: word(4), headerSize: word(8), recordSize: word(12), count: word(16), recordsPtr: word(20), overflowed: word(24) }};
  if (header.magic !== UI_ABI.magic || header.headerSize !== UI_ABI.headerSize || header.recordSize !== UI_ABI.recordSize) throw new Error("invalid Lean UI ABI header");
  return header;
}}
'''
(root / "ui_abi.js").write_text(js)

dts = '''export interface UiBatchHeader { magic: number; version: number; headerSize: number; recordSize: number; count: number; recordsPtr: number; overflowed: number }
export declare const UI_ABI: Readonly<{ magic: number; version: number; headerSize: number; recordSize: number; effect: Readonly<Record<string, number>>; handler: Readonly<Record<string, number>> }>;
export declare function readUiBatch(memory: WebAssembly.Memory, ptr: number): UiBatchHeader;
'''
(root / "ui_abi.d.ts").write_text(dts)
